const wait = ms => new Promise(resolve => setTimeout(resolve, ms));
const until = async predicate => { const end = performance.now() + 3500; while (!predicate() && performance.now() < end) await wait(20); return predicate(); };
const post = body => webkit.messageHandlers.lilt.postMessage(body);
const checks = [];
const check = (name, pass) => checks.push({ name, pass: Boolean(pass) });
post({ action: 'focusAction', command: 'reset' }); await wait(100);
post({ action: 'focusConfigure', activity: 'deepWork', minutes: 1 });
await until(() => Lilt.inspect().focus.duration === 60);
post({ action: 'focusAction', command: 'start' }); await until(() => Lilt.inspect().focus.phase === 'running');
Lilt.setView('shelf', { animate: false }); Lilt.setOpen(false);
const music = Lilt.inspect().music;
post({ action: 'testFocus', remaining: 1 });
await until(() => Lilt.inspect().focus.phase === 'completed');
check('timer completes natively while folded on another tab', Lilt.inspect().focus.phase === 'completed' && !Lilt.inspect().open && Lilt.inspect().view === 'shelf');
check('timer completion does not change selected music', Lilt.inspect().music.id === music.id && Lilt.inspect().music.playing === music.playing);
post({ action: 'focusAction', command: 'extend' }); await until(() => Lilt.inspect().focus.phase === 'running');
check('extension uses a persisted native deadline', Lilt.inspect().focus.deadline > Date.now() && Lilt.inspect().focus.remaining >= 298);
post({ action: 'focusAction', command: 'pause' }); await until(() => Lilt.inspect().focus.phase === 'paused');
const left = Lilt.inspect().focus.remaining; await wait(1100);
check('paused standalone timer remains paused in the background', Lilt.inspect().focus.remaining === left && !Lilt.inspect().open);
post({ action: 'focusAction', command: 'reset' }); await until(() => Lilt.inspect().focus.phase === 'idle');
check('background checks leave no page errors', !Lilt.inspect().errors.length);
return { checks, state: Lilt.inspect() };
