const wait = ms => new Promise(resolve => setTimeout(resolve, ms));
const checks = [];
const check = (name, pass) => checks.push({ name, pass: Boolean(pass) });
const find = selector => document.querySelector(selector);
const post = body => window.webkit.messageHandlers.lilt.postMessage(body);
const until = async condition => { const limit = performance.now() + 3500; while (!condition() && performance.now() < limit) await wait(30); return condition(); };
const click = selector => find(selector).click();
const pointerClick = selector => find(selector).dispatchEvent(new MouseEvent('click', { bubbles: true, detail: 1 }));
const key = (element, value) => element.dispatchEvent(new KeyboardEvent('keydown', { key: value, bubbles: true, cancelable: true }));
await until(() => LiltSettings.inspect().ready);
const initial = LiltSettings.inspect();
check('native settings snapshot and bundled font are ready', initial.ready && document.fonts.check('14px "Familjen Grotesk"'));
check('settings loads no remote resources', performance.getEntriesByType('resource').every(entry => !entry.name.startsWith('http')));
check('initial selected player matches native settings', find(`[data-source="${initial.musicSource}"]`).getAttribute('aria-checked') === 'true');
const picker = find('.player-picker').getBoundingClientRect();
check('three player choices fit inside the window', picker.left >= 0 && picker.right <= innerWidth && [...document.querySelectorAll('[data-source]')].every(button => button.scrollWidth <= button.clientWidth));
check('inactive Focus content is excluded from interaction', find('#settings-focus').inert && find('#settings-focus').getAttribute('aria-hidden') === 'true');
if (!initial.musicBusy) {
  const target = initial.musicSource === 'spotify' ? 'appleMusic' : 'spotify';
  pointerClick(`[data-source="${target}"]`);
  await until(() => LiltSettings.inspect().musicSource === target && !LiltSettings.inspect().requested);
  check('player selection is confirmed natively without a playback action', LiltSettings.inspect().musicSource === target && find(`[data-source="${target}"]`).getAttribute('aria-checked') === 'true');
  await wait(60);
  const selection = find('.player-selection');
  const movingFrame = selection.getBoundingClientRect().toJSON();
  const contrastSafe = () => [...document.querySelectorAll('.player-option')].every(button => getComputedStyle(button).mixBlendMode === 'difference' && getComputedStyle(button).color === 'rgb(255, 255, 255)');
  check('player text and icons stay contrast-safe during the moving selection', contrastSafe() && selection.getAnimations().some(animation => animation.transitionProperty === 'transform') && Math.abs(movingFrame.left - find(`[data-source="${target}"]`).getBoundingClientRect().left) > 1);
  pointerClick(`[data-source="${initial.musicSource}"]`);
  await until(() => LiltSettings.inspect().musicSource === initial.musicSource && !LiltSettings.inspect().requested);
  check('quick reversal preserves contrast and retargets the existing transition', contrastSafe() && selection.getAnimations().some(animation => animation.transitionProperty === 'transform'));
  await wait(270);
  const current = find(`[data-source="${initial.musicSource}"]`);
  current.focus(); key(current, 'ArrowRight');
  const expected = ['spotify', 'appleMusic', 'meld'][(['spotify', 'appleMusic', 'meld'].indexOf(initial.musicSource) + 1) % 3];
  await until(() => LiltSettings.inspect().musicSource === expected && !LiltSettings.inspect().requested);
  check('arrow keys select a player through the native store', LiltSettings.inspect().musicSource === expected);
  check('keyboard focus follows the confirmed player selection', document.activeElement === find(`[data-source="${expected}"]`));
  check('keyboard player selection has no transition', find('.player-selection').getAnimations().length === 0);
  post({ action: 'settingsUpdate', changes: { musicSource: initial.musicSource } });
  await until(() => LiltSettings.inspect().musicSource === initial.musicSource);
}
const musicTab = find('#settings-tab-music');
musicTab.focus(); key(musicTab, 'ArrowDown');
check('keyboard section navigation selects Focus and moves focus', LiltSettings.inspect().section === 'focus' && document.activeElement === find('#settings-tab-focus'));
check('keyboard section switch is immediate and hides Music from interaction', find('#settings-music').inert && !find('#settings-focus').inert && find('#settings-focus').getAnimations().length === 0);
if (!initial.focusLocked) {
  const minutes = initial.focusMinutes === 50 ? 25 : 50;
  click(`[data-minutes="${minutes}"]`);
  await until(() => LiltSettings.inspect().focusMinutes === minutes && !LiltSettings.inspect().requested);
  check('duration preset persists through native settings', LiltSettings.inspect().focusMinutes === minutes && Number(find('#default-minutes').value) === minutes);
  const input = find('#default-minutes');
  input.value = '0'; input.dispatchEvent(new Event('input', { bubbles: true }));
  find('#duration-form').dispatchEvent(new Event('submit', { bubbles: true, cancelable: true }));
  check('invalid duration stays in the editor with an accessible error', !find('#duration-error').hidden && input.getAttribute('aria-invalid') === 'true' && LiltSettings.inspect().focusMinutes === minutes);
  key(input, 'Escape');
  check('Escape cancels the duration draft without closing settings', Number(input.value) === minutes && find('#duration-error').hidden);
  const activity = initial.focusActivity === 'deepWork' ? 'lightWork' : 'deepWork';
  click(`[data-activity="${activity}"]`);
  await until(() => LiltSettings.inspect().focusActivity === activity && !LiltSettings.inspect().requested);
  check('activity is confirmed natively', LiltSettings.inspect().focusActivity === activity);
  click('#brainfm-toggle');
  await until(() => LiltSettings.inspect().brainFMEnabled !== initial.brainFMEnabled && !LiltSettings.inspect().requested);
  check('Brain.fm switch is confirmed by the native store', LiltSettings.inspect().brainFMEnabled !== initial.brainFMEnabled && find('#brainfm-toggle').getAttribute('aria-checked') === String(!initial.brainFMEnabled));
  post({ action: 'settingsUpdate', changes: { focusMinutes: initial.focusMinutes, focusActivity: initial.focusActivity, brainFMEnabled: initial.brainFMEnabled } });
  await until(() => LiltSettings.inspect().focusMinutes === initial.focusMinutes && LiltSettings.inspect().focusActivity === initial.focusActivity && LiltSettings.inspect().brainFMEnabled === initial.brainFMEnabled);
}
const snapshot = LiltSettings.inspect();
LiltSettings.receiveSnapshot({ ...snapshot, musicBusy: true, focusLocked: true });
check('native command and session locks disable configuration', [...document.querySelectorAll('[data-source], [data-activity], [data-minutes], #default-minutes, #brainfm-toggle')].every(element => element.disabled));
check('locked focus provides an explanation', !find('[data-focus-locked]').hidden);
LiltSettings.receiveSnapshot(snapshot);
LiltSettings.configure({ reducedMotion: true });
LiltSettings.setSection('music');
await wait(20);
check('reduced motion disables all settings transitions', document.getAnimations().length === 0 && getComputedStyle(find('.player-selection')).transitionDuration === '0s');
LiltSettings.configure({ reducedMotion: false });
LiltSettings.setSection('music', { animate: false });
check('final native settings restored and runtime clean', LiltSettings.inspect().musicSource === initial.musicSource && LiltSettings.inspect().focusMinutes === initial.focusMinutes && LiltSettings.inspect().brainFMEnabled === initial.brainFMEnabled && LiltSettings.inspect().errors.length === 0);
return { nativeSettings: true, simulatedPlayers: true, checks, state: LiltSettings.inspect() };
