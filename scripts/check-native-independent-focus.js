const checks = [];
const check = (name, pass) => checks.push({ name, pass: Boolean(pass) });
const wait = ms => new Promise(resolve => setTimeout(resolve, ms));
const until = async predicate => { const end = performance.now() + 3500; while (!predicate() && performance.now() < end) await wait(25); return predicate(); };
const post = body => window.webkit.messageHandlers.lilt.postMessage(body);
const find = selector => document.querySelector(selector);
check('Focus is natively configured without Brain.fm', Lilt.inspect().focus.brainFMEnabled === false);
post({ action: 'focusAction', command: 'reset' });
post({ action: 'focusConfigure', activity: 'lightWork', minutes: 1 });
await until(() => Lilt.inspect().focus.duration === 60);
Lilt.setOpen(true); Lilt.setView('focus', { animate: false }); await wait(600);
check('timer controls describe independent Focus', find('[data-action="focus"]').getAttribute('aria-label').includes('focus') && !find('[data-action="focus"]').getAttribute('aria-label').includes('Brain.fm'));
find('[data-action="focus"]').click();
await until(() => Lilt.inspect().focus.phase === 'running');
check('start works with the native Brain.fm transport disabled', Lilt.inspect().focus.phase === 'running' && !Lilt.inspect().focus.error);
await until(() => Lilt.inspect().remaining < 60);
check('native standalone timer counts down', Lilt.inspect().remaining < 60 && Lilt.inspect().remaining > 55);
find('[data-action="focus"]').click();
await until(() => Lilt.inspect().focus.phase === 'paused');
const remaining = Lilt.inspect().remaining;
await wait(1100);
check('pause freezes standalone time', Lilt.inspect().remaining === remaining);
find('[data-action="focus"]').click();
await until(() => Lilt.inspect().focus.phase === 'running');
check('resume keeps the remaining duration', Lilt.inspect().remaining <= remaining && Lilt.inspect().remaining > remaining - 2);
Lilt.setOpen(false); await wait(600);
post({ action: 'testFocus', remaining: 1 });
await until(() => Lilt.inspect().focus.phase === 'completed');
check('native completion works while folded', Lilt.inspect().focus.phase === 'completed' && Lilt.inspect().remaining === 0 && !Lilt.inspect().open);
check('completion has no music permission error', !Lilt.inspect().focus.error && Lilt.inspect().focus.brainFMEnabled === false);
check('selected Focus shows its standalone completion in compact mode', Lilt.inspect().view === 'focus' && find('[data-compact="right"]').textContent === 'Done');
Lilt.setOpen(true); await wait(600);
check('visible Fold button is removed from the footer', !find('.notch-foot [data-action="fold"]') && Boolean(find('[data-action="settings"]')));
find('#tab-music').click();
check('a tab remains interactive without folding', Lilt.inspect().open && Lilt.inspect().view === 'music');
find('.music-note').dispatchEvent(new MouseEvent('click', { bubbles: true }));
check('free surface folds the Notch', !Lilt.inspect().open);
check('no JavaScript errors', Lilt.inspect().errors.length === 0);
return { nativeStandaloneTimer: true, brainFMTransport: 'disabled', checks, state: Lilt.inspect() };
