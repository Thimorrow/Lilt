const checks = [];
const check = (name, pass) => checks.push({ name, pass: Boolean(pass) });
const wait = ms => new Promise(resolve => setTimeout(resolve, ms));
const until = async predicate => { const deadline = performance.now() + 3500; while (!predicate() && performance.now() < deadline) await wait(20); return predicate(); };
const post = body => webkit.messageHandlers.lilt.postMessage(body);
Lilt.setOpen(true); Lilt.setView('shelf', { animate: false }); await wait(650);
post({ action: 'shelfAction', command: 'clear' }); await until(() => Lilt.inspect().shelf.length === 0);
post({ action: 'testShelfPaste', names: ['first.txt', 'folder', 'second.txt'] }); await wait(100);
post({ action: 'testShelfKey', keyCode: 9 });
await until(() => Lilt.inspect().shelf.length === 3);
check('Command V pastes file and folder references from isolated pasteboard', Lilt.inspect().shelf.map(file => file.name).join(',') === 'first.txt,folder,second.txt');
check('folder is rendered without a text-only file type', Lilt.inspect().shelf[1]?.kind === 'FOLDER' && document.querySelectorAll('.file-icon svg').length >= 1);
const ids = Lilt.inspect().shelf.map(file => file.id);
post({ action: 'shelfAction', command: 'remove', ids: ids.slice(0, 2) });
await until(() => Lilt.inspect().shelf.length === 1);
check('removal exposes visible Undo', !document.querySelector('[data-action="shelf-undo"]').hidden);
post({ action: 'testShelfKey', keyCode: 6 });
await until(() => Lilt.inspect().shelf.length === 3);
check('Command Z restores order and original reference IDs', Lilt.inspect().shelf.map(file => file.id).join(',') === ids.join(','));
post({ action: 'testShelfKey', keyCode: 9 }); await wait(120);
check('pasting same references again creates no duplicates', Lilt.inspect().shelf.length === 3);
document.querySelector('[data-action="clear"]').click(); await until(() => !Lilt.inspect().shelf.length);
check('cleared Shelf retains accessible Undo', !document.querySelector('[data-action="shelf-undo"]').hidden && !document.querySelector('.shelf-actions').hidden);
document.querySelector('[data-action="shelf-undo"]').click(); await until(() => Lilt.inspect().shelf.length === 3);
check('Undo button restores a cleared Shelf', Lilt.inspect().shelf.length === 3);
check('no page errors', Lilt.inspect().errors.length === 0);
return { checks, state: Lilt.inspect() };
