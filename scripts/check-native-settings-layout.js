await document.fonts.ready;
const checks=[];
const check=(name,pass)=>checks.push({name,pass:Boolean(pass)});
const wait=ms=>new Promise(r=>setTimeout(r,ms));
const find=selector=>document.querySelector(selector);
const fits=element=>{const r=element.getBoundingClientRect();return r.left>=0&&r.right<=innerWidth&&r.top>=0&&r.bottom<=innerHeight;};
LiltSettings.setSection('focus',{animate:false});
await wait(50);
const label=find('#activity-label').getBoundingClientRect();
const control=find('.activity-picker').getBoundingClientRect();
check('activity label and control share a centered row',Math.abs((label.top+label.height/2)-(control.top+control.height/2))<2);
check('focus fields fit without horizontal overflow',fits(find('#default-minutes'))&&fits(find('.activity-picker'))&&fits(find('#brainfm-toggle')));
check('focus content scrolls within the window',find('.section-stack').scrollWidth<=find('.section-stack').clientWidth+1);
check('all settings navigation is visible',fits(find('.settings-nav'))&&fits(find('.sidebar-bottom')));
LiltSettings.setSection('music',{animate:false});
await wait(30);
check('player options fit the resized window',[...document.querySelectorAll('[data-source]')].every(fits));
check('selected player stays singular',document.querySelectorAll('[data-source][aria-checked="true"]').length===1);
check('settings has no runtime errors',LiltSettings.inspect().errors.length===0);
LiltSettings.setSection('focus',{animate:false});
return {viewport:{width:innerWidth,height:innerHeight},checks,state:LiltSettings.inspect()};
