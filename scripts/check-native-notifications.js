check('outside close clears text', cleared() && !Lilt.inspect().open);
await wait(300);
Lilt.configure({ reducedMotion: true });
inject({ title: 'Reduced motion synthetic text' });
await wait(150);
check('reduced motion configured', document.documentElement.classList.contains('reduce-motion'));
check('reduced motion uses existing shell', Lilt.inspect().notification.visible && document.documentElement.classList.contains('reduce-motion'));
check('reduced motion removes shell transition duration', getComputedStyle(document.querySelector('#notch')).transitionDuration.split(',').every(value => parseFloat(value) <= .001));
banner.querySelector('button').click();
await wait(150);
check('Dismiss removes text and announcements', cleared() && !document.querySelector('[data-announce]').textContent);
inject({ title: 'Expiry synthetic text' });
await wait(150);
check('expiry fixture displayed', Lilt.inspect().notification.visible);
await wait(8800);
check('native automatic expiry folds and clears', cleared() && !Lilt.inspect().open);
Lilt.setOpen(true);
await wait(100);
check('normal selected tab restored', Lilt.inspect().view === 'focus' && !document.querySelector('#view-focus').inert && document.querySelector('#view-focus').getAttribute('aria-hidden') === 'false');
Lilt.setOpen(false);
check('no JavaScript errors', Lilt.inspect().errors.length === 0);
return { checks, notification: Lilt.inspect().notification, simulated: true, captureEvidence: false };
