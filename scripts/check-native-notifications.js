await wait(150);
check('Escape clears and restores selected tab', cleared() && !Lilt.inspect().open && Lilt.inspect().view === 'focus');
inject({ title: 'Outside synthetic text' });
await wait(150);
document.body.dispatchEvent(new PointerEvent('pointerdown', { bubbles: true }));
