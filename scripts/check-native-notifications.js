const wait = ms => new Promise(resolve => setTimeout(resolve, ms));
const checks = [];
const check = (name, pass) => checks.push({ name, pass: Boolean(pass) });
const send = body => window.webkit.messageHandlers.lilt.postMessage(body);
const banner = document.querySelector('.notification-banner');
const source = banner.querySelector('[data-banner-source]');
const title = banner.querySelector('[data-banner-title]');
const body = banner.querySelector('[data-banner-body]');
const inject = fields => send({ action: 'testNotification', ...fields });
const cleared = () => banner.hidden && banner.inert && !source.textContent && !title.textContent && !body.textContent;
for (let attempt = 0; attempt < 40 && !Lilt.inspect().ready; attempt++) await wait(100);
check('native bridge ready', Lilt.inspect().ready);
Lilt.setOpen(false);
Lilt.setView('shelf', { animate: false });
await wait(600);
const hostile = '<img src=x onerror="window.bannerInjection=true">';
inject({ title: hostile, source: 'Synthetic fixture', body: '<script>throw new Error("executed")</script>' });
await wait(650);
check('synthetic banner opens existing shell', Lilt.inspect().open && Lilt.inspect().notification.visible);
check('hostile text stays plaintext', title.textContent === hostile && !banner.querySelector('img,script') && !window.bannerInjection);
check('notification text omitted from general diagnostics', !JSON.stringify(Lilt.inspect()).includes(hostile));
check('normal panels inert and hidden from accessibility', [...document.querySelectorAll('.view')].every(view => view.inert && view.getAttribute('aria-hidden') === 'true'));
check('banner is below physical notch', banner.getBoundingClientRect().top >= parseFloat(getComputedStyle(document.documentElement).getPropertyValue('--hardware-height')) - 1);
check('dismiss is named and has a 44px target', banner.querySelector('button').getAttribute('aria-label') && banner.querySelector('button').getBoundingClientRect().height >= 44);
inject({ title: 'No backlog' });
await wait(100);
check('second notification does not replace visible item', title.textContent === hostile);
Lilt.receiveNotificationBanner({ id: '00000000-0000-0000-0000-000000000000', clear: true });
check('stale clear identity is ignored', Lilt.inspect().notification.visible);
inject({ expire: true });
Lilt.setView('focus', { animate: false });
await wait(150);
check('tab takes ownership without folding', cleared() && Lilt.inspect().open && Lilt.inspect().view === 'focus');
inject({ expire: true });
await wait(100);
check('stale expiry cannot fold user panel', Lilt.inspect().open);
inject({ title: 'Dropped while user panel open' });
await wait(100);
check('open user panel drops notification', cleared());
Lilt.setOpen(false);
await wait(50);
inject({ title: 'Clear synthetic text' });
await wait(150);
inject({ clear: true });
await wait(150);
check('native clear folds and removes hidden text', cleared() && !Lilt.inspect().open);
inject({ title: 'Escape synthetic text' });
await wait(150);
