const wait = ms => new Promise(resolve => setTimeout(resolve, ms));
const checks = [];
const check = (name, pass) => checks.push({ name, pass: Boolean(pass) });
const send = value => window.webkit.messageHandlers.lilt.postMessage(value);
for (let attempt = 0; attempt < 40 && !window.LiltSettings?.inspect().ready; attempt++) await wait(100);
check('native settings ready', window.LiltSettings?.inspect().ready);
LiltSettings.setSection('general', { animate: false });
send({ action: 'settingsUpdate', changes: { notificationBannersEnabled: false } });
await wait(150);
check('notification opt-in is a boolean and defaults can be off', LiltSettings.inspect().notificationBannersEnabled === false);
const toggle = document.querySelector('[data-toggle="notificationBannersEnabled"]');
check('opt-in has explicit separate consent copy', toggle.getAttribute('aria-describedby') === 'notifications-consent' && document.querySelector('#notifications-consent').textContent.includes('separate from Brain.fm'));
toggle.click();
await wait(200);
check('native confirms enabled setting', LiltSettings.inspect().notificationBannersEnabled === true && !LiltSettings.inspect().requested);
check('diagnostic capture stays disabled even with opt-in', LiltSettings.inspect().notificationCaptureStatus === 'diagnostic');
check('permission settings action is disabled in diagnostics', document.querySelector('[data-action="notification-settings"]').disabled);
check('synthetic Preview remains available', !document.querySelector('[data-action="notification-preview"]').disabled);
document.querySelector('[data-action="notification-preview"]').click();
await wait(200);
toggle.click();
await wait(200);
check('disable is confirmed and persisted in native snapshot', LiltSettings.inspect().notificationBannersEnabled === false && !LiltSettings.inspect().requested);
check('no settings JavaScript errors', LiltSettings.inspect().errors.length === 0);
return { checks, simulated: true, captureEvidence: false };
