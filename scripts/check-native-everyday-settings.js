const checks = [];
const check = (name, pass) => checks.push({ name, pass: Boolean(pass) });
const wait = ms => new Promise(resolve => setTimeout(resolve, ms));
const until = async predicate => { const deadline = performance.now() + 3500; while (!predicate() && performance.now() < deadline) await wait(20); return predicate(); };
const post = body => webkit.messageHandlers.lilt.postMessage(body);
const click = selector => document.querySelector(selector).click();
LiltSettings.setSection('general', { animate: false });
click('[data-action="shortcut-record"]');
await until(() => LiltSettings.inspect().recordingShortcut);
check('shortcut recorder visibly starts', LiltSettings.inspect().recordingShortcut && document.querySelector('[data-shortcut-label]').textContent === 'Press shortcut…');
post({ action: 'testShortcutKey', keyCode: 3, modifiers: 0 }); await wait(120);
check('unmodified letter is rejected while recording continues', LiltSettings.inspect().recordingShortcut && document.querySelector('[data-shortcut-recording]').textContent.includes('Control'));
post({ action: 'testShortcutKey', keyCode: 3, modifiers: 1179648 });
await until(() => !LiltSettings.inspect().recordingShortcut && LiltSettings.inspect().shortcut?.keyCode === 3);
check('native keyboard capture saves Command Shift F', LiltSettings.inspect().shortcut?.keyCode === 3 && LiltSettings.inspect().shortcut.modifiers === 768 && LiltSettings.inspect().shortcutLabel.includes('⇧⌘'));
click('[data-action="shortcut-record"]'); await until(() => LiltSettings.inspect().recordingShortcut);
post({ action: 'testShortcutKey', keyCode: 53, modifiers: 0 });
await until(() => !LiltSettings.inspect().recordingShortcut);
check('Escape cancels and preserves saved binding', LiltSettings.inspect().shortcut?.keyCode === 3);
click('[data-action="shortcut-reset"]');
await until(() => LiltSettings.inspect().shortcut?.keyCode === 37 && !LiltSettings.inspect().requested);
check('reset restores the default without a stuck save', LiltSettings.inspect().shortcut?.modifiers === 6144 && !LiltSettings.inspect().requested);
LiltSettings.setSection('focus', { animate: false });
if (LiltSettings.inspect().focusNotificationsEnabled) { click('#focus-notification-toggle'); await until(() => !LiltSettings.inspect().focusNotificationsEnabled); }
click('#focus-notification-toggle'); await until(() => LiltSettings.inspect().focusNotificationsEnabled);
check('timer notification opt-in is independent and diagnostic-only', LiltSettings.inspect().focusNotificationsEnabled && LiltSettings.inspect().focusNotificationStatus === 'diagnostic');
click('#focus-notification-toggle'); await until(() => !LiltSettings.inspect().focusNotificationsEnabled);
check('timer notifications can be disabled', !LiltSettings.inspect().focusNotificationsEnabled);
check('no settings runtime errors', LiltSettings.inspect().errors.length === 0 && !LiltSettings.inspect().error);
return { checks, state: LiltSettings.inspect() };
